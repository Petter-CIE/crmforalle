import { start } from "./lib.mjs";
const v = await start("06-oppgaver");
const P = () => v.page;
const TITLE = "Bestill prøvesokker til Skarvvik";

v.title("Slik bruker du oppgaver", "Frister, påminnelser og alt om kunden på ett sted");
await v.go("/app/oppgaver");
await v.shot({ cursor: [2000, 1500], fade: 0.5 });
const form = P().locator("form", { has: P().locator("input[name=title]") }).first();
const title = form.locator("input[name=title]");
v.zoom(await v.union([title, form.getByRole("button", { name: "Legg til" })], 100), 0.9);
v.step("Steg 1 av 4", "Skriv hva som skal gjøres, og velg frist", 1.0);
await v.clickOn(title);
await v.typeInto(title, TITLE, 3);
const due = form.locator("input[name=due]");
await v.clickOn(due, { dur: 0.7 });
await due.pressSequentially("09102026");
await v.shot({ hold: 0.8 });

v.step("Steg 2 av 4", "Koble oppgaven til kunden", 0.8);
const comp = form.getByPlaceholder("Bedrift (valgfritt)");
await v.clickOn(comp);
await v.typeInto(comp, "Skarv", 1);
const o1 = P().getByRole("option", { name: /Skarvvik IL/ }).first();
await o1.waitFor();
await P().waitForTimeout(300);
await v.shot({ hold: 0.6 });
await v.clickOn(o1, { dur: 0.6 });
await P().waitForTimeout(300);
await v.shot({ hold: 0.3 });
const pers = form.getByPlaceholder(/Kontakt/);
await v.clickOn(pers);
await P().getByRole("option", { name: /Ola/ }).first().waitFor();
await P().waitForTimeout(400);
await v.shot({ hold: 1.0 });
v.note("Kontaktfeltet viser bare kontaktene i bedriften du valgte", 2.6);
const ola = P().getByRole("option", { name: /Ola Berg/ }).first();
await v.clickOn(ola, { dur: 0.6 });
await P().waitForTimeout(300);
await v.shot({ hold: 0.5 });
await v.clickOn(form.getByRole("button", { name: "Legg til" }));
await v.settle(900);
v.zoom(null, 0.7);
await v.shot({ fade: 0.2, hold: 1.0 });
v.note("Oppgaven ligger i listen – og på kortet til Skarvvik IL og Ola Berg", 3.0);

v.step("Steg 3 av 4", "Åpne oppgaven for å oppdatere status, skrive notater og legge ved filer", 0.6);
await v.clickOn(P().getByText(TITLE).first());
await P().waitForURL(/\/app\/oppgaver\/[0-9a-f-]{36}/);
await v.settle(900);
await v.shot({ fade: 0.3, hold: 0.8 });
await v.clickOn(P().getByRole("button", { name: "Pågår" }));
await v.settle(700);
await v.shot({ hold: 0.8 });
const note = P().getByPlaceholder("Skriv et notat eller en oppdatering …");
await v.clickOn(note);
await v.typeInto(note, "Ola ønsker prøver i str. 39–41 og 42–44.", 5);
await v.clickOn(P().getByRole("button", { name: "Legg til notat" }));
await v.settle(900);
await v.shot({ hold: 1.0 });
const file = P().locator("input[type=file]");
const fileBtn = file.locator("xpath=..");
await v.clickOn(fileBtn, { real: false });
await file.setInputFiles(v.dir + "../../Storrelsesliste.pdf");
await P().getByText("Storrelsesliste.pdf").first().waitFor({ timeout: 20000 });
await v.settle(600);
const fname = P().getByText("Storrelsesliste.pdf").first();
v.move(await v.center(fname), 0.8);
await v.shot({ hold: 0.4 });
v.zoom(await v.union([P().getByText("Vedlegg", { exact: true }).first(), fname, fileBtn], 120), 0.9);
v.note("Vedlegg: PDF, bilder, Word, Excel og mer – opptil 25 MB", 3.0);
v.zoom(null, 0.7);

v.step("Steg 4 av 4", "Se oppgavene i kalenderen din: Konto og sikkerhet → Kalender", 0.6);
await v.clickOn(P().getByRole("link", { name: "Konto og sikkerhet" }).first());
await P().waitForURL("**/app/konto**");
await v.settle();
await v.shot({ fade: 0.3 });
const kal = P().getByRole("heading", { name: "Kalender", exact: true });
v.move(await v.center(kal), 1.0);
v.zoom(await v.union([kal, kal.locator("xpath=following::button[1]")], 120), 0.9);
v.note("Lenken fungerer med Google Kalender, Outlook og iPhone", 3.4);
v.zoom(null, 0.7);
v.end();
await v.finish();
